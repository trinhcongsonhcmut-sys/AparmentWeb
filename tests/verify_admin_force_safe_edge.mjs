runTest('proposeConnections bảo vệ cạnh đã được duyệt an toàn (không bị đổi lại thành blocked)', () => {
  const graphStore = new WaypointGraphStore();

  const w3 = graphStore.createWaypoint('W3', { x: 0, y: 1.5, z: 0 });
  const w4 = graphStore.createWaypoint('W4', { x: 3, y: 1.5, z: 0 });

  // Create edge and confirm safe
  graphStore.createEdge(w3.id, w4.id, {
    status: 'valid',
    direction: 'bidirectional',
    confirmedByAdmin: true,
  });

  // Run proposeConnections with a mock collision function that would normally fail (isLineSafeFn = false)
  const isLineSafeAlwaysFalse = () => false;

  const res = graphStore.proposeConnections(
    { maxDistance: 8.0, maxHeightDiff: 1.5, overwriteExisting: true },
    isLineSafeAlwaysFalse
  );

  const finalEdge = graphStore.getEdgeBetween(w3.id, w4.id);
  assert.strictEqual(finalEdge.status, 'valid', 'Cạnh đã duyệt an toàn không được đổi thành blocked');
  assert.strictEqual(finalEdge.confirmedByAdmin, true, 'confirmedByAdmin vẫn phải là true');
  console.log(`  ✓ proposeConnections giữ nguyên trạng thái valid và confirmedByAdmin cho cạnh`);
});

