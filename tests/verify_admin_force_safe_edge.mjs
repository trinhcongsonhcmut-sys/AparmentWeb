runTest('Thêm waypoint mới vẫn duy trì tính năng tự động kết nối với các waypoint lân cận', () => {
  const graphStore = new WaypointGraphStore();

  const w1 = graphStore.createWaypoint('W1', { x: 0, y: 1.5, z: 0 });
  const w2 = graphStore.createWaypoint('W2', { x: 2, y: 1.5, z: 0 });

  // Add existing edge between w1 and w2 (admin confirmed)
  graphStore.createEdge(w1.id, w2.id, {
    status: 'valid',
    direction: 'bidirectional',
    confirmedByAdmin: true,
  });

  // Now user adds W3 at (4, 1.5, 0) - within 8m of W2 and W1
  const w3 = graphStore.createWaypoint('W3', { x: 4, y: 1.5, z: 0 });

  // Propose connections (mocking EditorApp.ts handleGlobalWaypointPlacementClick behavior)
  const isLineSafeFn = (pA, pB) => true;
  const res = graphStore.proposeConnections(
    { maxDistance: 8.0, maxHeightDiff: 1.5, bidirectional: true },
    isLineSafeFn
  );

  const edgeW2W3 = graphStore.getEdgeBetween(w2.id, w3.id);
  assert.ok(edgeW2W3, 'Phải tự động tạo kết nối giữa W2 và W3');
  assert.strictEqual(edgeW2W3.status, 'valid');

  const edgeW1W2 = graphStore.getEdgeBetween(w1.id, w2.id);
  assert.strictEqual(edgeW1W2.confirmedByAdmin, true, 'Cạnh cũ w1-w2 vẫn nguyên vẹn');

  console.log(`  ✓ Waypoint mới tự động kết nối với các điểm trong bán kính, không ảnh hưởng cạnh cũ`);
});

