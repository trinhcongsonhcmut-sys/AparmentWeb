runTest('pickEdge trong GlobalGraphVisualizer nhận diện chính xác cạnh 3D', () => {
  const scene = new THREE.Scene();
  const visualizer = new GlobalGraphVisualizer(scene);

  const waypoints = [
    { id: 'w3', name: 'Waypoint 3', position: { x: 0, y: 1.5, z: 0 }, status: 'active', floor: 1 },
    { id: 'w4', name: 'Waypoint 4', position: { x: 4, y: 1.5, z: 0 }, status: 'active', floor: 1 },
  ];

  const edges = [
    {
      id: 'edge_w3_w4',
      fromWaypointId: 'w3',
      toWaypointId: 'w4',
      direction: 'bidirectional',
      status: 'blocked',
      distance: 4.0,
      costWeight: 1.0,
      autoGenerated: true,
      confirmedByAdmin: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    },
  ];

  visualizer.updateVisuals(waypoints, edges, null, null);

  // Cast a ray from above pointing down towards the midpoint (2, 1.5, 0)
  const rayOrigin = new THREE.Vector3(2.05, 5.0, 0.05); // Slightly off center (~7cm offset)
  const rayDir = new THREE.Vector3(0, -1, 0).normalize();
  const raycaster = new THREE.Raycaster(rayOrigin, rayDir, 0.1, 100);

  const pickedEdgeId = visualizer.pickEdge(raycaster);
  assert.strictEqual(pickedEdgeId, 'edge_w3_w4', 'Raycast phải nhặt trúng cạnh edge_w3_w4');
  console.log(`  ✓ pickEdge bắt trúng cạnh ID: ${pickedEdgeId} tại tọa độ chuột`);
});

