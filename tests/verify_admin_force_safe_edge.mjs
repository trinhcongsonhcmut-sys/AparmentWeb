// TEST 2: Cưỡng chế an toàn chuyển cạnh 'blocked' thành 'valid'
// -------------------------------------------------------------
runTest('Cưỡng chế chấp thuận an toàn chuyển đổi trạng thái cạnh thành valid & confirmedByAdmin', () => {
  const graphStore = new WaypointGraphStore();
  const history = new CommandHistory();

  const w3 = graphStore.createWaypoint('W3', { x: 0, y: 1.5, z: 0 });
  const w4 = graphStore.createWaypoint('W4', { x: 4, y: 1.5, z: 0 });

  // Create initially blocked edge
  const edge = graphStore.createEdge(w3.id, w4.id, {
    status: 'blocked',
    direction: 'bidirectional',
    confirmedByAdmin: false,
  });

  assert.strictEqual(edge.status, 'blocked');
  assert.strictEqual(edge.confirmedByAdmin, false);

  // Execute admin force safe command
  const oldEdge = JSON.parse(JSON.stringify(edge));
  const newEdge = JSON.parse(JSON.stringify(edge));
  newEdge.status = 'valid';
  newEdge.confirmedByAdmin = true;

  const cmd = new UpdateEdgeCommand(graphStore, oldEdge, newEdge);
  history.execute(cmd);

  const updatedEdge = graphStore.getEdge(edge.id);
  assert.strictEqual(updatedEdge.status, 'valid', 'Trạng thái phải là valid');
  assert.strictEqual(updatedEdge.confirmedByAdmin, true, 'confirmedByAdmin phải là true');

  // Verify Undo/Redo works
  history.undo();
  assert.strictEqual(graphStore.getEdge(edge.id).status, 'blocked');
  history.redo();
  assert.strictEqual(graphStore.getEdge(edge.id).status, 'valid');

  console.log(`  ✓ Cạnh W3 ⇄ W4 đã được cưỡng chế an toàn và hỗ trợ hoàn tác Undo/Redo`);
});

