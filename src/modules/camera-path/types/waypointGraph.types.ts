import type { Vector3D } from '../../hotspots/types/hotspot.types.ts';
import type { CameraWaypoint } from './cameraPath.types.ts';

export type WaypointStatus = 'active' | 'draft' | 'disabled';
export type EdgeDirection = 'bidirectional' | 'unidirectional';
export type EdgeStatus = 'valid' | 'blocked' | 'untested' | 'needs_confirmation';

export interface WaypointEdge {
  id: string;                      // UUID
  fromWaypointId: string;          // Node A
  toWaypointId: string;            // Node B
  direction: EdgeDirection;        // 'bidirectional' | 'unidirectional'
  status: EdgeStatus;              // 'valid' | 'blocked' | 'untested' | 'needs_confirmation'
  distance: number;                // Euclidean length in meters
  estimatedDurationSeconds?: number;// Expected travel time
  costWeight?: number;             // Multiplier or custom penalty (default 1.0)
  autoGenerated?: boolean;         // Suggested by auto-connect
  confirmedByAdmin?: boolean;      // Verified / approved by admin
  notes?: string;
  createdAt: string;
  updatedAt: string;
}

export interface AutoConnectOptions {
  maxDistance?: number;            // Search radius in meters (default 8.0)
  maxHeightDiff?: number;          // Maximum height difference in meters (default 1.5)
  clearanceRadius?: number;        // Raycast clearance radius in meters (default 0.25)
  bidirectional?: boolean;         // Create bidirectional edges (default true)
  overwriteExisting?: boolean;     // Whether to overwrite existing edges between same nodes
}

export interface AutoConnectResult {
  proposedCount: number;
  validCount: number;
  blockedCount: number;
  needsConfirmationCount: number;
  edges: WaypointEdge[];
}

export interface DisconnectedComponent {
  componentIndex: number;
  waypointIds: string[];
}

export interface EdgeObstacleIssue {
  edgeId: string;
  fromWaypointId: string;
  toWaypointId: string;
  reason: string;
}

export interface GraphDiagnosticsReport {
  timestamp: string;
  totalWaypoints: number;
  activeWaypoints: number;
  totalEdges: number;
  validEdges: number;
  blockedEdges: number;
  needsConfirmationEdges: number;
  isolatedWaypointIds: string[];
  components: DisconnectedComponent[];
  obstacleIssues: EdgeObstacleIssue[];
  outOfBoundsWaypointIds: string[];
  unreachableHotspotIds: string[];
  isHealthy: boolean;
}

